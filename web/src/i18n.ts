const dict: Record<Lang, Record<Key, string>> = { fi, sv, en };

export const LANGS: Lang[] = ['fi', 'sv', 'en'];
export const LANG_NAMES: Record<Lang, string> = { fi: 'Suomi', sv: 'Svenska', en: 'English' };

export type TFn = (key: Key, vars?: Record<string, string | number>) => string;

export function makeT(lang: Lang): TFn {
  const table = dict[lang];
  return (key, vars) => {
    const s = table[key] ?? fi[key] ?? key;
    if (!vars) return s;
    return s.replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
  };
}

const STORE_KEY = 'aimo.lang';

export function loadLang(): Lang {
  try {
    const saved = localStorage.getItem(STORE_KEY);
    if (saved === 'fi' || saved === 'sv' || saved === 'en') return saved;
  } catch {
    /* storage unavailable */
  }
  return 'fi';
}

export function saveLang(lang: Lang): void {
  try {
    localStorage.setItem(STORE_KEY, lang);
  } catch {
    /* storage unavailable */
  }
}
